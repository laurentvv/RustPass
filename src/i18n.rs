/// Substitutes `{}` placeholders in a translated template with `args`, in order.
///
/// `format!` only accepts literal format strings, so localized templates that carry
/// runtime values go through this helper instead.
#[must_use]
pub fn fill(template: &str, args: &[&dyn std::fmt::Display]) -> String {
    let mut out = String::with_capacity(template.len() + 16);
    let mut rest = template;
    for arg in args {
        match rest.find("{}") {
            Some(pos) => {
                out.push_str(&rest[..pos]);
                out.push_str(&arg.to_string());
                rest = &rest[pos + 2..];
            }
            None => break,
        }
    }
    out.push_str(rest);
    out
}

/// Returns the static translation bundle for `lang`.
#[must_use]
pub const fn texts(lang: Language) -> &'static Texts {
    match lang {
        Language::English => &EN,
        Language::French => &FR,
    }
}
